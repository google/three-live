/// Raw vertex, normal, UV, and index buffers generated by native geometry kernels.
#[derive(Debug, Clone)]
pub struct NativeGeometry {
    pub positions: Vec<f32>,
    pub normals: Vec<f32>,
    pub uvs: Vec<f32>,
    pub indices: Vec<u32>,
}

impl NativeGeometry {
    /// Converts the native buffers into a JavaScript Object containing Float32Array and
    /// Uint32Array using single-allocation 64-byte aligned ArrayBuffers.
    pub fn to_js_object(&self, context: &mut Context) -> JsResult<JsObject> {
        let obj = JsObject::with_object_proto(context.intrinsics());

        let pos_arr = js_float32_array_from_slice(&self.positions, context)?;
        let norm_arr = js_float32_array_from_slice(&self.normals, context)?;
        let uv_arr = js_float32_array_from_slice(&self.uvs, context)?;
        let idx_arr = js_uint32_array_from_slice(&self.indices, context)?;

        obj.set(js_string!("positions"), pos_arr, false, context)?;
        obj.set(js_string!("normals"), norm_arr, false, context)?;
        obj.set(js_string!("uvs"), uv_arr, false, context)?;
        obj.set(js_string!("indices"), idx_arr, false, context)?;

        Ok(obj)
    }
}

/// Generates a TorusKnot geometry using native vectorized trigonometry and Frenet framing.
pub fn generate_torus_knot(
    radius: f32,
    tube: f32,
    tubular_segments: usize,
    radial_segments: usize,
    p: f32,
    q: f32,
) -> NativeGeometry {
    let tubular_segments = tubular_segments.clamp(3, 2048);
    let radial_segments = radial_segments.clamp(3, 2048);
    let vertex_count = (tubular_segments + 1) * (radial_segments + 1);

    let mut positions = Vec::with_capacity(vertex_count * 3);
    let mut normals = Vec::with_capacity(vertex_count * 3);
    let mut uvs = Vec::with_capacity(vertex_count * 2);
    let mut indices = Vec::with_capacity(tubular_segments * radial_segments * 6);

    let mut cos_sin_table = Vec::with_capacity((radial_segments + 1) * 3);
    let radial_step = std::f32::consts::TAU / radial_segments as f32;
    for j in 0..=radial_segments {
        let v = j as f32 * radial_step;
        cos_sin_table.push(-tube * v.cos());
        cos_sin_table.push(tube * v.sin());
        cos_sin_table.push(j as f32 / radial_segments as f32);
    }

    let safe_p = if !p.is_finite() || p.abs() < 1e-5 { 2.0 } else { p };
    let safe_q = if !q.is_finite() { 3.0 } else { q };
    let calculate_position_on_curve = |u: f32| -> [f32; 3] {
        let cu = u.cos();
        let su = u.sin();
        let qu_over_p = (safe_q / safe_p) * u;
        let cs = qu_over_p.cos();
        let r0 = radius * (2.0 + cs) * 0.5;
        [r0 * cu, r0 * su, radius * qu_over_p.sin() * 0.5]
    };

    let sub_vec =
        |a: [f32; 3], b: [f32; 3]| -> [f32; 3] { [a[0] - b[0], a[1] - b[1], a[2] - b[2]] };
    let add_vec =
        |a: [f32; 3], b: [f32; 3]| -> [f32; 3] { [a[0] + b[0], a[1] + b[1], a[2] + b[2]] };
    let cross_vec = |a: [f32; 3], b: [f32; 3]| -> [f32; 3] {
        [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]]
    };
    let norm_vec = |v: [f32; 3]| -> [f32; 3] {
        let len = (v[0] * v[0] + v[1] * v[1] + v[2] * v[2]).sqrt();
        if len > 1e-5 {
            [v[0] / len, v[1] / len, v[2] / len]
        } else {
            [0.0, 0.0, 1.0]
        }
    };

    for i in 0..=tubular_segments {
        let u_ratio = i as f32 / tubular_segments as f32;
        let u = u_ratio * p * std::f32::consts::TAU;
        let p1 = calculate_position_on_curve(u);
        let p2 = calculate_position_on_curve(u + 0.01);

        let t = norm_vec(sub_vec(p2, p1));
        let mut n = norm_vec(add_vec(p1, p2));
        let b = norm_vec(cross_vec(t, n));
        n = norm_vec(cross_vec(b, t));

        for j in 0..=radial_segments {
            let idx = j * 3;
            let cx = cos_sin_table[idx];
            let cy = cos_sin_table[idx + 1];
            let v_ratio = cos_sin_table[idx + 2];

            let dx = cx * n[0] + cy * b[0];
            let dy = cx * n[1] + cy * b[1];
            let dz = cx * n[2] + cy * b[2];

            positions.push(p1[0] + dx);
            positions.push(p1[1] + dy);
            positions.push(p1[2] + dz);

            let len = (dx * dx + dy * dy + dz * dz).sqrt();
            if len > 1e-5 {
                normals.push(dx / len);
                normals.push(dy / len);
                normals.push(dz / len);
            } else {
                normals.push(0.0);
                normals.push(0.0);
                normals.push(1.0);
            }

            uvs.push(u_ratio);
            uvs.push(v_ratio);
        }
    }

    let stride = (radial_segments + 1) as u32;
    for j in 1..=tubular_segments as u32 {
        let row1 = stride * (j - 1);
        let row2 = row1 + stride;
        for i in 1..=radial_segments as u32 {
            let i_minus_1 = i - 1;
            let a = row1 + i_minus_1;
            let b = row2 + i_minus_1;
            let c = row2 + i;
            let d = row1 + i;
            indices.push(a);
            indices.push(b);
            indices.push(d);
            indices.push(b);
            indices.push(c);
            indices.push(d);
        }
    }

    NativeGeometry { positions, normals, uvs, indices }
}

/// Generates a UV Sphere geometry using native spherical coordinates.
pub fn generate_sphere(
    radius: f32,
    width_segments: usize,
    height_segments: usize,
) -> NativeGeometry {
    let width_segments = width_segments.clamp(3, 2048);
    let height_segments = height_segments.clamp(2, 2048);
    let vertex_count = (width_segments + 1) * (height_segments + 1);

    let mut positions = Vec::with_capacity(vertex_count * 3);
    let mut normals = Vec::with_capacity(vertex_count * 3);
    let mut uvs = Vec::with_capacity(vertex_count * 2);
    let mut indices = Vec::with_capacity(width_segments * height_segments * 6);

    let mut grid = Vec::with_capacity(height_segments + 1);

    for iy in 0..=height_segments {
        let mut vertices_row = Vec::with_capacity(width_segments + 1);
        let v = iy as f32 / height_segments as f32;
        let phi = v * std::f32::consts::PI;
        let sin_phi = phi.sin();
        let cos_phi = phi.cos();

        for ix in 0..=width_segments {
            let u = ix as f32 / width_segments as f32;
            let theta = u * std::f32::consts::TAU;

            let x = -radius * theta.cos() * sin_phi;
            let y = radius * cos_phi;
            let z = radius * theta.sin() * sin_phi;

            positions.push(x);
            positions.push(y);
            positions.push(z);

            let len = (x * x + y * y + z * z).sqrt();
            if len > 1e-5 {
                normals.push(x / len);
                normals.push(y / len);
                normals.push(z / len);
            } else {
                normals.push(0.0);
                normals.push(1.0);
                normals.push(0.0);
            }

            uvs.push(u);
            uvs.push(1.0 - v);

            vertices_row.push(((positions.len() / 3) - 1) as u32);
        }
        grid.push(vertices_row);
    }

    for iy in 0..height_segments {
        for ix in 0..width_segments {
            let a = grid[iy][ix + 1];
            let b = grid[iy][ix];
            let c = grid[iy + 1][ix];
            let d = grid[iy + 1][ix + 1];

            if iy != 0 {
                indices.push(a);
                indices.push(b);
                indices.push(d);
            }
            if iy != height_segments - 1 {
                indices.push(b);
                indices.push(c);
                indices.push(d);
            }
        }
    }

    NativeGeometry { positions, normals, uvs, indices }
}

/// Generates a Cylinder geometry using native trigonometric rings and caps.
pub fn generate_cylinder(
    radius_top: f32,
    radius_bottom: f32,
    height: f32,
    radial_segments: usize,
) -> NativeGeometry {
    let radial_segments = radial_segments.clamp(3, 2048);
    let half_height = height / 2.0;

    let mut positions = Vec::new();
    let mut normals = Vec::new();
    let mut uvs = Vec::new();
    let mut indices = Vec::new();

    for y in 0..=1 {
        let v = y as f32;
        let radius = if y == 0 { radius_top } else { radius_bottom };
        let py = if y == 0 { half_height } else { -half_height };

        for x in 0..=radial_segments {
            let u = x as f32 / radial_segments as f32;
            let theta = u * std::f32::consts::TAU;
            let sin_theta = theta.sin();
            let cos_theta = theta.cos();

            positions.push(radius * sin_theta);
            positions.push(py);
            positions.push(radius * cos_theta);

            normals.push(sin_theta);
            normals.push(0.0);
            normals.push(cos_theta);

            uvs.push(u);
            uvs.push(1.0 - v);
        }
    }

    for x in 0..radial_segments as u32 {
        let a = x;
        let b = x + radial_segments as u32 + 1;
        let c = x + radial_segments as u32 + 2;
        let d = x + 1;

        indices.push(a);
        indices.push(b);
        indices.push(d);
        indices.push(b);
        indices.push(c);
        indices.push(d);
    }

    if radius_top > 0.0 {
        let center_idx = (positions.len() / 3) as u32;
        positions.extend_from_slice(&[0.0, half_height, 0.0]);
        normals.extend_from_slice(&[0.0, 1.0, 0.0]);
        uvs.extend_from_slice(&[0.5, 0.5]);

        let rim_start = (positions.len() / 3) as u32;
        for x in 0..=radial_segments {
            let u = x as f32 / radial_segments as f32;
            let theta = u * std::f32::consts::TAU;
            let sin_theta = theta.sin();
            let cos_theta = theta.cos();

            positions.extend_from_slice(&[
                radius_top * sin_theta,
                half_height,
                radius_top * cos_theta,
            ]);
            normals.extend_from_slice(&[0.0, 1.0, 0.0]);
            uvs.extend_from_slice(&[cos_theta * 0.5 + 0.5, sin_theta * 0.5 + 0.5]);
        }

        for x in 0..radial_segments as u32 {
            indices.push(center_idx);
            indices.push(rim_start + x);
            indices.push(rim_start + x + 1);
        }
    }

    if radius_bottom > 0.0 {
        let center_idx = (positions.len() / 3) as u32;
        positions.extend_from_slice(&[0.0, -half_height, 0.0]);
        normals.extend_from_slice(&[0.0, -1.0, 0.0]);
        uvs.extend_from_slice(&[0.5, 0.5]);

        let rim_start = (positions.len() / 3) as u32;
        for x in 0..=radial_segments {
            let u = x as f32 / radial_segments as f32;
            let theta = u * std::f32::consts::TAU;
            let sin_theta = theta.sin();
            let cos_theta = theta.cos();

            positions.extend_from_slice(&[
                radius_bottom * sin_theta,
                -half_height,
                radius_bottom * cos_theta,
            ]);
            normals.extend_from_slice(&[0.0, -1.0, 0.0]);
            uvs.extend_from_slice(&[cos_theta * 0.5 + 0.5, 1.0 - (sin_theta * 0.5 + 0.5)]);
        }

        for x in 0..radial_segments as u32 {
            indices.push(center_idx);
            indices.push(rim_start + x + 1);
            indices.push(rim_start + x);
        }
    }

    NativeGeometry { positions, normals, uvs, indices }
}

